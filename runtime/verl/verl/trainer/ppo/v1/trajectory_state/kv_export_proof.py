"""Exact protocol migration from Project B f91c201d; see MIGRATION.md."""
from __future__ import annotations

import hashlib
from typing import Callable

from .snapshot import token_digest

def confirm_export(*, token_ids: list[int], prefix_tokens: int,
                   policy_identity: dict, ordered_object_keys: list[str],
                   read_object: Callable[[str], bytes], master_address: str,
                   source_completed_tokens: int | None) -> dict | None:
    """Return no reference unless actual completed reads prove every object.

    Keys must be generated by the frozen engine's native prefix hashing and KV
    layout adapter. Export metrics must come from that same request/isolated
    source window. Probe reads and hashing are setup work, outside performance
    timing. Missing objects leave the committed token snapshot usable.
    """
    if (type(prefix_tokens) is not int or not 0 < prefix_tokens <= len(token_ids)
            or type(source_completed_tokens) is not int or source_completed_tokens < prefix_tokens
            or not ordered_object_keys or len(set(ordered_object_keys)) != len(ordered_object_keys)):
        return None
    objects = []
    try:
        for key in ordered_object_keys:
            payload = read_object(key)
            if not isinstance(payload, bytes) or not payload:
                return None
            objects.append({"key": key, "bytes": len(payload),
                "sha256": hashlib.sha256(payload).hexdigest()})
    except Exception:
        return None
    return {"export_complete": True, "prefix_tokens": prefix_tokens,
        "token_digest": token_digest(token_ids[:prefix_tokens]), "policy_identity": policy_identity,
        "kv_bytes": sum(item["bytes"] for item in objects), "storage_reference": {
            "backend": "mooncake", "master_address": master_address,
            "objects": objects, "source_completed_tokens": source_completed_tokens}}


def validate_export_reference(ref: dict, *, token_ids: list[int], policy_identity: dict) -> None:
    """Require completed object receipts, not an opaque handle or candidate."""
    prefix = ref.get("prefix_tokens")
    storage = ref.get("storage_reference")
    if (ref.get("export_complete") is not True or type(prefix) is not int
            or not 0 < prefix <= len(token_ids)
            or ref.get("token_digest") != token_digest(token_ids[:prefix])
            or ref.get("policy_identity") != policy_identity or not isinstance(storage, dict)
            or storage.get("backend") != "mooncake" or not storage.get("master_address")
            or type(storage.get("source_completed_tokens")) is not int
            or storage["source_completed_tokens"] < prefix):
        raise ValueError("KV reference lacks completed export/prefix/identity proof")
    objects = storage.get("objects")
    if not isinstance(objects, list) or not objects:
        raise ValueError("KV reference requires actual object read receipts")
    keys = []
    for obj in objects:
        if (not isinstance(obj, dict) or not isinstance(obj.get("key"), str) or not obj["key"]
                or type(obj.get("bytes")) is not int or obj["bytes"] <= 0
                or not isinstance(obj.get("sha256"), str) or len(obj["sha256"]) != 64
                or any(c not in "0123456789abcdef" for c in obj["sha256"])):
            raise ValueError("invalid KV object read receipt")
        keys.append(obj["key"])
    if (len(set(keys)) != len(keys) or type(ref.get("kv_bytes")) is not int
            or ref["kv_bytes"] != sum(obj["bytes"] for obj in objects)):
        raise ValueError("KV bytes do not match the actual object receipts")
